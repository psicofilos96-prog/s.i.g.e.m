"""SECRETARIA no navegador: busca estudante real → declara início → prévia → emite → reproduz → abre emitido → PDF A4 com QR
→ verificação pública sem sessão."""
import asyncio, json, os, datetime, subprocess
from playwright.async_api import async_playwright
B = "http://localhost:8080"; OUT = "/tmp/fsec"; SH = f"{OUT}/shots"; os.makedirs(SH, exist_ok=True)
cfg = json.load(open(f"{OUT}/s.json"))
def p(ok, l, x=""): print(f"{'PASS' if ok else 'FAIL'} {l} {x}".rstrip())
today = datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=-3))).date()
async def main():
    async with async_playwright() as pw:
        br = await pw.chromium.launch(headless=True)
        ctx = await br.new_context(viewport={"width": 1280, "height": 1800}); pg = await ctx.new_page()
        errs = []; pg.on("pageerror", lambda e: errs.append(str(e)[:160]))
        await pg.goto(B + "/"); await pg.evaluate("([k,v]) => localStorage.setItem(k, v)", [cfg["key"], json.dumps(cfg["session"])])
        await pg.goto(f"{B}/documentos-escolares?escola={cfg['schoolA']}"); await pg.wait_for_timeout(6000)
        sec = pg.locator("section[aria-labelledby=busca]"); await sec.wait_for(timeout=20000)
        await sec.get_by_label("Nome ou identificador").fill(cfg["studentName"][:12]); await sec.get_by_role("button", name="Buscar").click()
        row = sec.get_by_role("listitem").filter(has_text=cfg["studentName"]).first
        await row.wait_for(timeout=15000)
        t = await row.inner_text(); p("início: não registrado" in t, "busca acha matrícula real; início aparece como não registrado (nunca inferido)", t.replace("\n", " ")[:160])
        await row.get_by_role("button", name="Declarar início").click()
        g = pg.get_by_role("group", name="Declarar início da matrícula")
        start = (today - datetime.timedelta(days=60)).isoformat()
        await g.get_by_label("Data de início").fill(start.split("-")[2] + "/" + start.split("-")[1] + "/" + start.split("-")[0])
        await g.get_by_label("Motivo").fill("Teste técnico: data conforme livro de matrícula (sintético)")
        await g.get_by_role("button", name="Gravar declaração").click(); await pg.wait_for_timeout(3000)
        s = " | ".join(await sec.get_by_role("status").all_inner_texts()); p("declarado" in s, "secretaria declara início pela tela", s)
        row = sec.get_by_role("listitem").filter(has_text=cfg["studentName"]).first
        p("declarado pela secretaria" in await row.inner_text(), "lista mostra a origem da data (declaração da secretaria)")
        await row.get_by_role("button", name="Usar este estudante").click()
        await pg.get_by_role("button", name="Abrir aluno").click(); await pg.wait_for_timeout(4000)
        sel = pg.get_by_role("combobox", name="Modelo", exact=True); opts = await sel.locator("option").all_inner_texts()
        lab = next((o for o in opts if "DECLARAÇÃO DE MATRÍCULA" in o), None); p(lab is not None, "modelo versionado listado", str(opts)[:120])
        await sel.select_option(label=lab); await pg.wait_for_timeout(1500)
        prev = pg.locator("section[aria-labelledby=prev]"); txt = await prev.inner_text()
        p(cfg["studentName"] in txt and "sem registro]" not in txt.split("desde")[1][:30], "prévia com nome real e data declarada", txt[:200].replace("\n", " "))
        await pg.screenshot(path=f"{SH}/1_previa.png")
        await prev.get_by_role("button", name="Emitir documento").click(); await pg.wait_for_timeout(4000)
        s = " | ".join(await pg.get_by_role("status").all_inner_texts()); p("Emitido" in s and "DM-" in s, "emissão registrada com código e número", s[:160])
        hist = pg.locator("section[aria-labelledby=hist]"); items = hist.get_by_role("listitem")
        p(await items.count() == 1, "histórico mostra 1 emissão", str(await items.count()))
        await items.first.get_by_role("button", name="Reproduzir").click(); await pg.wait_for_timeout(3500)
        p(await items.count() == 2, "reprodução registrada como segunda via (mesmos dados congelados)", str(await items.count()))
        orig = items.filter(has_not_text="reprodução").first
        await orig.get_by_role("button", name="Ver").click(); await pg.wait_for_timeout(1500)
        view = pg.locator("section[aria-labelledby=view]")
        qr = await view.locator("svg[data-testid=cx-qr-svg]").count(); p(qr == 1, "documento emitido traz QR de verificação")
        code = (await view.inner_text()).split("código ")[1].split(" ")[0].strip()
        await pg.emulate_media(media="print"); await pg.pdf(path=f"{OUT}/declaracao.pdf", format="A4", print_background=True)
        await pg.emulate_media(media="screen")
        info = subprocess.run(["pdfinfo", f"{OUT}/declaracao.pdf"], capture_output=True, text=True).stdout
        p("595" in info, "PDF A4 gerado", [l for l in info.splitlines() if "Page size" in l or l.startswith("Pages")].__str__())
        subprocess.run(["pdftoppm", "-png", "-r", "70", "-f", "1", "-l", "1", f"{OUT}/declaracao.pdf", f"{SH}/pdf"])
        p(not errs, "sem erros de página", str(errs)[:200]); await ctx.close()
        a = await br.new_context(viewport={"width": 1280, "height": 1800}); ap = await a.new_page()
        await ap.goto(f"{B}/verificar/documento/{code}"); await ap.wait_for_timeout(5000)
        vt = await ap.inner_text("body"); await ap.screenshot(path=f"{SH}/2_verificacao.png")
        p(("válid" in vt.lower()) and cfg["studentName"] not in vt, "verificação pública sem sessão: válido e sem nome do estudante", vt[:160].replace("\n", " "))
        await br.close()
asyncio.run(main())
